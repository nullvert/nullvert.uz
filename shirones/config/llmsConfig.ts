import type { LlmsConfig } from "@/types/llmsConfig";
import { withUserConfig } from "@/utils/config-overlay.ts";

/**
 * ─────────────────────────────────────────────────────────────────────────────
 *  Shirone: Руководство по конфигурации LLMs.txt и AI-friendly системы контента
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * Следует принципу «ноль лишней нагрузки» и спецификации https://llmstxt.org/:
 * - Предоставляет структурированный Markdown-индекс для LLM (ChatGPT, Claude, Perplexity, Cursor и т.д.);
 * - Чистая серверная статическая генерация `/llms.txt` (индекс) и `/llms-full.txt` (полный дамп контента);
 * - 0 КБ дополнительного клиентского JS, нулевое влияние на скорость пользователей;
 * - Безопасность: автоматически исключает зашифрованные статьи (encrypted: true) и черновики (draft: true).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 【Автоматические механизмы (файл обычно не требует ручной правки)】
 * ─────────────────────────────────────────────────────────────────────────────
 * 1. Публичные статьи (Articles):
 *    - При сборке система автоматически сканирует Markdown-файлы;
 *    - Автоматически извлекаются заголовки, ссылки, описания и теги;
 * 2. Базовая информация:
 *    - Название, подзаголовок и био наследуются из `siteConfig` и `profileConfig`;
 * 3. Очистка текста:
 *    - В `/llms-full.txt` раскрываются блоки `<llm-only>` и удаляются теги `<llm-exclude>`.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 【Популярные сценарии настройки】
 * ─────────────────────────────────────────────────────────────────────────────
 * Сценарий A: Конфигурация по умолчанию (рекомендуется)
 *   - Оставьте настройки как есть: статьи попадут в `/llms.txt` и `/llms-full.txt`.
 *
 * Сценарий B: Полное отключение эндпоинтов для LLM
 *   - Установите `enable: false` (ссылки будут возвращать 404, файлы не генерируются).
 *
 * Сценарий C: Генерация только краткого индекса без полного дампа текстов
 *   - Установите `generateFull: false` (создается только `/llms.txt`, без `/llms-full.txt`).
 *
 * Сценарий D: Исключение чувствительных тегов
 *   - Добавьте имена тегов в `excludeTags`, например: `excludeTags: ["secret", "private", "diary"]`.
 * ─────────────────────────────────────────────────────────────────────────────
 */
export const llmsConfig: LlmsConfig = withUserConfig("llms", {
	/**
	 * Включить генерацию эндпоинтов /llms.txt и /llms-full.txt
	 * - true (по умолчанию): генерация текстовых Markdown файлов в dist/;
	 * - false: отключить генерацию (отдает 404).
	 */
	enable: true,

	/**
	 * Генерировать ли файл /llms-full.txt с полными текстами всех статей
	 * - true (по умолчанию): полный дамп текстов без черновиков для AI / RAG;
	 * - false: только оглавление /llms.txt.
	 */
	generateFull: true,

	/**
	 * Описание сайта для LLM (опционально)
	 * - Пустая строка: откат к `siteConfig.subtitle` или `profileConfig.bio`;
	 * - При заполнении: используется указанное пользовательское описание.
	 */
	siteSummary: "",

	/**
	 * Максимальная длина аннотации статьи в индексе /llms.txt (по умолчанию 200 символов)
	 * - При превышении обрезается с многоточием "…";
	 * - Не влияет на полный текст в /llms-full.txt.
	 */
	descriptionMaxLength: 200,

	/**
	 * Черный список тегов (опционально)
	 * - Статьи с любым из этих тегов исключаются из /llms.txt и /llms-full.txt.
	 */
	excludeTags: ["secret", "private"],

	/**
	 * Черный список категорий (опционально)
	 * - Статьи указанных категорий полностью исключаются из выдачи для LLM.
	 */
	excludeCategories: [],

	/**
	 * Список основных страниц (Core Pages)
	 * - Знакомит модель с ключевыми разделами блога;
	 * - Можно указывать относительные пути ("/about/") или внешние URL;
	 * - При пустом массиве [] используются стандартные страницы по умолчанию.
	 */
	corePages: [
		{
			title: "Home",
			url: "/",
			description: "Main blog entrance and latest post stream.",
		},
		{
			title: "About",
			url: "/about/",
			description: "Author profile, technical stack, and background.",
		},
		{
			title: "Archive",
			url: "/archive/",
			description: "Chronological index of all published writings.",
		},
	],

	/**
	 * Пользовательские дополнительные секции (опционально)
	 * - Позволяют рекомендовать AI Agent внешние репозитории, API или ресурсы;
	 * - По умолчанию пустой массив [].
	 */
	customSections: [],
});
